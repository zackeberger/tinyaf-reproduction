"""Generate C weight, model geometry, threshold, and filter coefficient headers.
"""

from pathlib import Path

import numpy as np
from scipy.signal import butter, sosfilt_zi

from python_model.runtime import THRESHOLDS, load_model

ROOT = Path(__file__).resolve().parents[1]


def main():
    """Write S/M/L model headers and the supported sampling-rate filter table."""
    for rung in "SML":
        name = f"TINYAF-{rung}"
        net = load_model(name)
        layers = [
            ("CONV1", net.conv1),
            ("CONV2", net.conv2),
            ("BEAT_CONV", net.beat_conv),
        ]
        out = [
            "/* Generated by python -m src.export_weights; do not edit. */",
            "#ifndef TINYAF_MODEL_WEIGHTS_H",
            "#define TINYAF_MODEL_WEIGHTS_H",
            f'#define MODEL_RUNG "{rung}"',
            f"#define MODEL_THRESHOLD {float(np.float32(THRESHOLDS[name])):.9g}f",
            f"#define MODEL_PARAMS {sum(p.numel() for p in net.parameters())}",
            f"#define EMBED {net.embed}",
            f"#define BEAT_CH {net.beat_ch}",
            f"#define HIDDEN {net.fc1.out_features}",
            f"#define PER_BEAT {net.per_beat}",
            "#define CONV1_LEN 17",
            "#define CONV2_LEN 9",
        ]
        for name, layer in layers:
            for field, value in [
                ("IN", layer.in_channels),
                ("OUT", layer.out_channels),
                ("KERNEL", layer.kernel_size[0]),
                ("STRIDE", layer.stride[0]),
                ("PAD", layer.padding[0]),
            ]:
                out.append(f"#define {name}_{field} {value}")
        for name, tensor in net.state_dict().items():
            values = tensor.numpy().reshape(-1)
            cname = name.upper().replace(".", "_")
            out.append(f"static const float {cname}[{len(values)}] = {{")
            for i in range(0, len(values), 8):
                out.append(
                    "  " + ", ".join(float(x).hex() + "f" for x in values[i : i + 8]) + ","
                )
            out.append("};")
        out.append("#endif")
        (ROOT / "c_model" / f"TINYAF_{rung}_weights.h").write_text(
            "\n".join(out) + "\n"
        )
    out = [
        "/* SciPy 1.16.0 butter(2, 40, fs=fs), sosfilt_zi; generated. */",
        "typedef struct { int fs; TinyAFReal b0,b1,b2,a1,a2,z0,z1; } FilterCoefficients;",
        "static const FilterCoefficients FILTERS[] = {",
    ]
    for fs in [100, 128, 200, 250, 256, 300, 360, 500, 1000]:
        sos = butter(2, 40, fs=fs, output="sos")
        zi = sosfilt_zi(sos)[0]
        values = [*sos[0, :3], *sos[0, 4:], *zi]
        coefficients = ", ".join(f"R({float(x).hex()})" for x in values)
        out.append(f"  {{{fs}, {coefficients}}},")
    out.append("};")
    (ROOT / "c_model" / "filter_coefficients.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
